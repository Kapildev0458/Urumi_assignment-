# Builds every app under apps\ that has a Dockerfile and pushes it to the k3d registry.
# Writes the tags to charts\platform\values-images.yaml (git-ignored), which deploy.ps1 applies,
# so each build rolls the pods even though the chart's default tag did not change.
# Usage: powershell -ExecutionPolicy Bypass -File scripts\build-images.ps1 [-Only woo-mcp] [-Registry localhost:5000/urumi]
param(
    [string[]]$Only = @(),
    [string]$Registry = 'localhost:5000/urumi'
)
. "$PSScriptRoot\lib.ps1"
# Through "powershell -File", "-Only a,b" arrives as the single string "a,b".
$Only = @($Only | ForEach-Object { $_ -split ',' } | Where-Object { $_ })

$tag = 'dev-' + (Get-Date -Format 'yyyyMMdd-HHmmss')
$valuesFile = Join-Path $RepoRoot 'charts\platform\values-images.yaml'

# Keep tags of apps not rebuilt this time.
$tags = [ordered]@{}
if (Test-Path $valuesFile) {
    $current = $null
    foreach ($line in Get-Content $valuesFile) {
        if ($line -match '^([\w-]+):\s*$') { $current = $Matches[1] }
        elseif ($current -and $line -match '^\s+tag:\s*"?([^"]+)"?') { $tags[$current] = $Matches[1] }
    }
}

$apps = Get-ChildItem (Join-Path $RepoRoot 'apps') -Directory |
    Where-Object { Test-Path (Join-Path $_.FullName 'Dockerfile') } |
    Where-Object { $Only.Count -eq 0 -or $Only -contains $_.Name }
if (-not $apps) { throw 'No apps with a Dockerfile matched.' }

foreach ($app in $apps) {
    $image = "$Registry/$($app.Name):$tag"
    Write-Step "Building $image"
    Invoke-Native docker @('build', '-t', $image, $app.FullName)
    Write-Step "Pushing $image"
    Invoke-Native docker @('push', $image)
    $tags[$app.Name] = $tag
}

$lines = @('# Generated by scripts\build-images.ps1. Do not edit or commit.')
foreach ($name in $tags.Keys) {
    $lines += "${name}:"
    $lines += '  image:'
    $lines += "    tag: `"$($tags[$name])`""
}
Set-Content -Path $valuesFile -Value $lines -Encoding ascii
Write-Host "Image tags written to $valuesFile" -ForegroundColor Green
