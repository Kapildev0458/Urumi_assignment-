#!/usr/bin/env bash
# Turns a fresh Ubuntu VPS into a single-node k3s cluster and deploys the platform with the same
# charts as local, using values-prod.yaml. Run it from the repo root on the VPS. Safe to re-run:
# it upgrades the release with freshly built images.
#
# Usage: sudo DOMAIN=<public-ip>.sslip.io bash scripts/vps-setup.sh            # with Let's Encrypt TLS
#        sudo DOMAIN=<public-ip>.sslip.io TLS=false bash scripts/vps-setup.sh  # plain HTTP
set -euo pipefail

DOMAIN=${DOMAIN:?Set DOMAIN, for example DOMAIN=20.1.2.3.sslip.io}
TLS=${TLS:-true}
K3S_VERSION=${K3S_VERSION:-v1.35.5+k3s1}           # same k3s version as the local k3d cluster
CERT_MANAGER_VERSION=${CERT_MANAGER_VERSION:-v1.18.2}
RELEASE=urumi
NAMESPACE=urumi
REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
CHART="$REPO_ROOT/charts/platform"
export KUBECONFIG=/etc/rancher/k3s/k3s.yaml

step() { printf '\n==> %s\n' "$*"; }

step "k3s $K3S_VERSION"
if ! command -v k3s >/dev/null; then
  # The public IP goes into the API server certificate, so kubectl can also be used from a laptop.
  PUBLIC_IP=$(curl -fsS https://api.ipify.org || true)
  curl -sfL https://get.k3s.io | INSTALL_K3S_VERSION="$K3S_VERSION" sh -s - \
    --write-kubeconfig-mode 600 ${PUBLIC_IP:+--tls-san "$PUBLIC_IP"}
fi
until kubectl get nodes >/dev/null 2>&1; do sleep 2; done
kubectl wait --for=condition=Ready node --all --timeout=180s
# Traefik is installed by k3s itself; wait for it before creating Ingresses.
until kubectl -n kube-system get deploy traefik >/dev/null 2>&1; do sleep 3; done
kubectl -n kube-system rollout status deploy/traefik --timeout=300s

step "Helm and Docker (Docker only builds the images)"
command -v helm >/dev/null || curl -fsSL https://raw.githubusercontent.com/helm/helm/main/scripts/get-helm-3 | bash
command -v docker >/dev/null || { apt-get update -qq && apt-get install -y -qq docker.io; }

if [ "$TLS" = true ]; then
  step "cert-manager $CERT_MANAGER_VERSION and the letsencrypt-prod ClusterIssuer"
  kubectl apply -f "https://github.com/cert-manager/cert-manager/releases/download/$CERT_MANAGER_VERSION/cert-manager.yaml"
  kubectl -n cert-manager rollout status deploy/cert-manager-webhook --timeout=300s
  # HTTP-01 challenges are answered through Traefik, so ports 80 and 443 must be open.
  until kubectl apply -f - <<'EOF'
apiVersion: cert-manager.io/v1
kind: ClusterIssuer
metadata:
  name: letsencrypt-prod
spec:
  acme:
    server: https://acme-v02.api.letsencrypt.org/directory
    privateKeySecretRef:
      name: letsencrypt-prod-account
    solvers:
      - http01:
          ingress:
            ingressClassName: traefik
EOF
  do sleep 5; done
fi

# No registry needed: build on the VPS and load the images straight into k3s's containerd.
# The tags go into values-images.yaml (git-ignored), exactly like scripts\build-images.ps1 locally.
step "Building images and importing them into k3s"
TAG="prod-$(date +%Y%m%d-%H%M%S)"
IMAGE_VALUES="$CHART/values-images.yaml"
echo "# Generated by scripts/vps-setup.sh. Do not edit or commit." > "$IMAGE_VALUES"
for dir in "$REPO_ROOT"/apps/*/; do
  app=$(basename "$dir")
  [ -f "$dir/Dockerfile" ] || continue
  image="localhost/urumi/$app:$TAG"
  echo "  $image"
  docker build -q -t "$image" "$dir" >/dev/null
  docker save "$image" | k3s ctr -n k8s.io images import - >/dev/null
  printf '%s:\n  image:\n    repository: localhost/urumi/%s\n    tag: "%s"\n' "$app" "$app" "$TAG" >> "$IMAGE_VALUES"
done

step "helm upgrade --install $RELEASE (values-prod.yaml, domain $DOMAIN, TLS $TLS)"
helm dependency update "$CHART" >/dev/null
EXTRA=()
if [ "$TLS" != true ]; then
  EXTRA=(--set store.ingress.tls.enabled=false --set gateway.ingress.tls.enabled=false
         --set dashboard.ingress.tls.enabled=false --set woo-mcp.store.publicTls=false)
fi
helm upgrade --install "$RELEASE" "$CHART" --namespace "$NAMESPACE" --create-namespace \
  -f "$CHART/values-prod.yaml" -f "$IMAGE_VALUES" --set global.domain="$DOMAIN" "${EXTRA[@]}" \
  --wait --timeout 20m

kubectl -n "$NAMESPACE" get pods,pvc,ingress
[ "$TLS" = true ] && kubectl -n "$NAMESPACE" get certificate
SCHEME=$([ "$TLS" = true ] && echo https || echo http)
cat <<EOF

Storefront: $SCHEME://store.$DOMAIN
Dashboard:  $SCHEME://app.$DOMAIN   (MCP endpoint: $SCHEME://app.$DOMAIN/mcp)
Admin login password:
  sudo k3s kubectl -n $NAMESPACE get secret $RELEASE-gateway-secrets -o jsonpath='{.data.admin-password}' | base64 -d
Chat agent: create the LLM Secret (see README, "Chat agent"), then
  sudo k3s kubectl -n $NAMESPACE rollout restart deployment $RELEASE-gateway
EOF
